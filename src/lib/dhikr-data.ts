export function getCurrentPrayerIndex(): number {
  const hour = new Date().getHours();
  if (hour >= 4 && hour < 10) return 0;
  if (hour >= 10 && hour < 15) return 1;
  if (hour >= 15 && hour < 18) return 2;
  if (hour >= 18 && hour < 20) return 3;
  return 4;
}

